// Round command: node ux/round.ts D-nn. Writes ux/rounds/D-nn/{report.md,round.json,shots/} and a row in
// ux/rounds/trend.md from the spec outputs in ux/out, against ux/baseline.json and the previous round.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Baseline, Metrics } from '../../ui/ux/ratchet-lib.ts';
import { metrics, readBots, readGates } from './metrics.ts';
import { RATCHET_VIEWPORT } from './viewports.ts';

const here = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2];
if (!id || !/^D-\d{2}$/.test(id)) {
  console.error('usage: node ux/round.ts D-nn');
  process.exit(2);
}
const out = join(here, 'out');
const roundsDir = join(here, 'rounds');
const dir = join(roundsDir, id);
mkdirSync(join(dir, 'shots'), { recursive: true });

const gates = readGates(out);
const bots = readBots(out);
const now = metrics(gates, bots);
const baseFile = join(here, 'baseline.json');
const base: Baseline | null = existsSync(baseFile) ? (JSON.parse(readFileSync(baseFile, 'utf8')) as Baseline) : null;
const prevId = existsSync(roundsDir) ? readdirSync(roundsDir).filter((d) => /^D-\d{2}$/.test(d) && d < id).sort().pop() : undefined;
const prev: Metrics | null =
  prevId && existsSync(join(roundsDir, prevId, 'round.json'))
    ? (JSON.parse(readFileSync(join(roundsDir, prevId, 'round.json'), 'utf8')) as { metrics: Metrics }).metrics
    : null;

const where = (g: { page: string; viewport: string; theme: string }): string => `${g.page || 'landing'} @ ${g.viewport} ${g.theme}`;
const lines: string[] = [`# ${id} docs round report`, '', `Generated by \`node ux/round.ts ${id}\` from \`ux/out\`.`, ''];
lines.push('## Gate problems at the gating sizes', '');
const problems = gates.filter((g) => g.gating).flatMap((g) => g.problems.map((p) => `${where(g)}: ${p}`));
lines.push(...(problems.length ? problems.map((p) => `- ${p}`) : ['None.']), '');
lines.push('## Measured-only sizes', '');
const measured = gates.filter((g) => !g.gating).flatMap((g) => g.problems.map((p) => `${where(g)}: ${p}`));
lines.push(...(measured.length ? measured.map((p) => `- ${p}`) : ['None.']), '');
lines.push('## Sideways scroll boxes at the ratchet size', '');
const boxes = gates.filter((g) => g.viewport === RATCHET_VIEWPORT && g.theme === 'light').flatMap((g) => g.scroll_boxes.map((b) => `${g.page || 'landing'}: ${b}`));
lines.push(...(boxes.length ? boxes.map((b) => `- ${b}`) : ['None.']), '');
lines.push('## Screen-only reader', '');
for (const b of [...bots].sort((a, c) => `${a.task}${a.viewport}${a.mode}`.localeCompare(`${c.task}${c.viewport}${c.mode}`))) {
  lines.push(
    `- ${b.task} @ ${b.viewport} by ${b.mode}: ${b.done ? 'done' : 'NOT DONE'}; ${b.actions} actions, ${b.looks} looks, ${b.steers} steers, ${b.keyboard_tabs} tabs; ${b.path.join(' | ')}${b.notes.length ? `; ${b.notes.join('; ')}` : ''}`,
  );
}
lines.push('', `## Metrics at ${RATCHET_VIEWPORT} (lower is better)`, '');
lines.push('| scenario | key | now | baseline | last round |', '|---|---|---|---|---|');
for (const [sc, keys] of Object.entries(now).sort()) {
  for (const [k, v] of Object.entries(keys).sort()) {
    lines.push(`| ${sc} | ${k} | ${v} | ${base?.scenarios[sc]?.[k]?.value ?? '–'} | ${prev?.[sc]?.[k] ?? '–'} |`);
  }
}
lines.push('', '## Not measured this round', '');
lines.push('- L4 keyed replay, L5 discoverability probe, L6 people: not run (operator-only).');
lines.push('- Questionnaire: no person ran the cards; the screen-only reader replaced them.', '');

const shots = join(out, 'gates', 'shots');
const kept: string[] = [];
if (existsSync(shots)) {
  for (const f of readdirSync(shots).filter((f) => f.includes(`@${RATCHET_VIEWPORT}-`) || f.includes('@390x844-')).sort()) {
    copyFileSync(join(shots, f), join(dir, 'shots', f));
    kept.push(f);
  }
  const pngs = kept.map((f) => join(dir, 'shots', f));
  if (pngs.length) spawnSync('pngquant', ['--quality=60-85', '--force', '--skip-if-larger', '--ext', '.png', ...pngs], { stdio: 'ignore' });
}
lines.push('## Contact sheet', '', ...kept.map((f) => `- [${f}](shots/${f})`), '');
writeFileSync(join(dir, 'report.md'), lines.join('\n'));
writeFileSync(join(dir, 'round.json'), JSON.stringify({ id, metrics: now, problems, measured, bots }, null, 2) + '\n');

const trend = join(roundsDir, 'trend.md');
const head = '# Docs UX trend\n\n| round | gate problems | measured-only problems | reader failures | keyboard failures |\n|---|---|---|---|---|\n';
const sum = (k: string): number => Object.values(now).reduce((a, m) => a + (m[k] ?? 0), 0);
const row = `| ${id} | ${problems.length} | ${measured.length} | ${sum('screen_only.failed')} | ${sum('screen_only.keyboard_failed')} |\n`;
const old = existsSync(trend) ? readFileSync(trend, 'utf8').split('\n').filter((l) => !l.startsWith(`| ${id} |`)).join('\n') : head;
writeFileSync(trend, (old.endsWith('\n') ? old : old + '\n') + row);
console.log(`${id}: ${problems.length} gate problems, ${measured.length} measured-only, ${bots.filter((b) => !b.done).length} reader runs not done; ${join(dir, 'report.md')}`);
