// Round command: node ux/round.ts R-nn. Writes ux/rounds/R-nn/{report.md,round.json,shots/} and a row in ux/rounds/trend.md
// from the spec outputs in ux/out, against ux/baseline.json and the previous round.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { metrics, RATCHET_VIEWPORT, readBots, readGates } from './metrics.ts';
import type { Baseline, Metrics } from './ratchet-lib.ts';

const here = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2];
if (!id || !/^R-\d{2}$/.test(id)) {
  console.error('usage: node ux/round.ts R-nn');
  process.exit(2);
}
const out = join(here, 'out');
const roundsDir = join(here, 'rounds');
const dir = join(roundsDir, id);
mkdirSync(join(dir, 'shots'), { recursive: true });

const gates = readGates(out);
const bots = readBots(out);
const now = metrics(gates, bots);
const baseFile = join(here, 'baseline.json');
const base: Baseline | null = existsSync(baseFile) ? (JSON.parse(readFileSync(baseFile, 'utf8')) as Baseline) : null;
const prevId = existsSync(roundsDir)
  ? readdirSync(roundsDir).filter((d) => /^R-\d{2}$/.test(d) && d < id).sort().pop()
  : undefined;
const prev: Metrics | null = prevId && existsSync(join(roundsDir, prevId, 'round.json'))
  ? (JSON.parse(readFileSync(join(roundsDir, prevId, 'round.json'), 'utf8')) as { metrics: Metrics }).metrics
  : null;

const lines: string[] = [`# ${id} round report`, '', `Generated by \`node ux/round.ts ${id}\` from \`ux/out\`.`, ''];
lines.push('## Gate problems at the gating sizes', '');
const gating = gates.filter((g) => g.gating);
const problems = gating.flatMap((g) => g.problems.map((p) => `${g.scenario} @ ${g.viewport}: ${p}`));
lines.push(...(problems.length ? problems.map((p) => `- ${p}`) : ['None.']), '');
lines.push('## Measured-only sizes', '');
const measured = gates.filter((g) => !g.gating).flatMap((g) => g.problems.map((p) => `${g.scenario} @ ${g.viewport}: ${p}`));
lines.push(...(measured.length ? [...new Set(measured)].map((p) => `- ${p}`) : ['None.']), '');
lines.push('## Screen-only user', '');
for (const b of [...bots].sort((a, c) => `${a.scenario}${a.viewport}${a.mode}`.localeCompare(`${c.scenario}${c.viewport}${c.mode}`))) {
  const flags = [b.done ? 'done' : 'NOT DONE', b.completion_miss ? 'completion_miss' : '', b.false_complete ? 'false_complete' : ''].filter(Boolean);
  lines.push(`- ${b.scenario} @ ${b.viewport} by ${b.mode}: ${flags.join(', ')}; ${b.actions} actions, ${b.looks} looks, ${b.keyboard_tabs} tabs${b.notes.length ? `; ${b.notes.join('; ')}` : ''}`);
}
lines.push('', `## Metrics at ${RATCHET_VIEWPORT} (lower is better)`, '');
lines.push('| scenario | key | now | baseline | last round |', '|---|---|---|---|---|');
for (const [sc, keys] of Object.entries(now).sort()) {
  for (const [k, v] of Object.entries(keys).sort()) {
    const b = base?.scenarios[sc]?.[k]?.value;
    const p = prev?.[sc]?.[k];
    lines.push(`| ${sc} | ${k} | ${v} | ${b ?? '–'} | ${p ?? '–'} |`);
  }
}
lines.push('', '## Not measured this round', '');
lines.push('- L4 keyed replay, L5 discoverability probe, L6 people: not run (no recorded sessions; operator-only).');
lines.push('- Questionnaire: no person ran the cards; the screen-only user replaced them.');
lines.push('');

const shots = join(out, 'gates', 'shots');
const kept: string[] = [];
if (existsSync(shots)) {
  for (const f of readdirSync(shots).filter((f) => f.includes(`@${RATCHET_VIEWPORT}-`)).sort()) {
    copyFileSync(join(shots, f), join(dir, 'shots', f));
    kept.push(f);
  }
  // The contact sheet is committed: quantise it when pngquant is installed (about 2.5 times smaller).
  const pngs = kept.map((f) => join(dir, 'shots', f));
  if (pngs.length) spawnSync('pngquant', ['--quality=60-85', '--force', '--skip-if-larger', '--ext', '.png', ...pngs], { stdio: 'ignore' });
}
lines.push('## Contact sheet', '', ...kept.map((f) => `- [${f}](shots/${f})`), '');
writeFileSync(join(dir, 'report.md'), lines.join('\n'));
writeFileSync(join(dir, 'round.json'), JSON.stringify({ id, metrics: now, problems, bots }, null, 2) + '\n');

const trend = join(roundsDir, 'trend.md');
const head = '# UX trend\n\n| round | gate problems | screen-only failures | keyboard failures |\n|---|---|---|---|\n';
const sum = (k: string): number => Object.values(now).reduce((a, m) => a + (m[k] ?? 0), 0);
const row = `| ${id} | ${problems.length} | ${sum('screen_only.failed')} | ${sum('screen_only.keyboard_failed')} |\n`;
const old = existsSync(trend) ? readFileSync(trend, 'utf8').split('\n').filter((l) => !l.startsWith(`| ${id} |`)).join('\n') : head;
writeFileSync(trend, (old.endsWith('\n') ? old : old + '\n') + row);
console.log(`${id}: ${problems.length} gate problems, ${bots.filter((b) => !b.done).length} screen-only tasks not done; ${join(dir, 'report.md')}`);
