// Round command: node ux/round.ts R-nn. Writes ux/rounds/R-nn/{report.md,round.json,shots/} and a row in ux/rounds/trend.md
// from the spec outputs in ux/out, against ux/baseline.json and the previous round. Exit 1 when a result file
// that a round writes (every scenario at every size, every task in both modes) is not in ux/out.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expectedFiles, metrics, missingFiles, RATCHET_VIEWPORT, readBots, readGates } from './metrics.ts';
import { compare, mainBaseline } from './ratchet-lib.ts';
import type { Baseline, Metrics } from './ratchet-lib.ts';
import { SCENARIOS } from './scenarios.ts';
import { VIEWPORTS, vpName } from './viewports.ts';

const here = dirname(fileURLToPath(import.meta.url));
const id = process.argv[2];
if (!id || !/^R-\d{2}$/.test(id)) {
  console.error('usage: node ux/round.ts R-nn');
  process.exit(2);
}
// A test runs the command on its own copies: UX_OUT, UX_ROUNDS and UX_BASELINE replace the three paths.
const out = process.env.UX_OUT ?? join(here, 'out');
const roundsDir = process.env.UX_ROUNDS ?? join(here, 'rounds');
const dir = join(roundsDir, id);
mkdirSync(join(dir, 'shots'), { recursive: true });

const gates = readGates(out);
const bots = readBots(out);
const now = metrics(gates, bots);
const baseFile = process.env.UX_BASELINE ?? join(here, 'baseline.json');
const base: Baseline | null = existsSync(baseFile) ? (JSON.parse(readFileSync(baseFile, 'utf8')) as Baseline) : null;
const prevId = existsSync(roundsDir)
  ? readdirSync(roundsDir).filter((d) => /^R-\d{2}$/.test(d) && d < id).sort().pop()
  : undefined;
const prev: Metrics | null = prevId && existsSync(join(roundsDir, prevId, 'round.json'))
  ? (JSON.parse(readFileSync(join(roundsDir, prevId, 'round.json'), 'utf8')) as { metrics: Metrics }).metrics
  : null;

// A test that crashes writes no result file. Each file a round expects and does not find is named,
// and counts as a gate problem or as a failure of the screen-only user in its mode.
const expected = expectedFiles(SCENARIOS, VIEWPORTS.map(vpName));
const missing = missingFiles(out, expected);
const missingCount = missing.gates.length + missing.bots.length;

/** Keys that rounds before R-11 wrote under another name, with the same value. */
const BEFORE_R11: Record<string, string> = { 'layout_shift.total': 'layout_shift.per_minute' };

const lines: string[] = [`# ${id} round report`, '', `Generated by \`node ux/round.ts ${id}\` from \`ux/out\`.`, ''];
lines.push('## Missing result files', '');
lines.push(
  `A round writes ${expected.gates.length} gate files and ${expected.bots.length} screen-only files: ${SCENARIOS.length} scenarios, ` +
    `${SCENARIOS.filter((sc) => sc.task).length} with a task, at ${VIEWPORTS.length} sizes, by pointer and by keyboard. ` +
    'A test that crashed wrote none: each file below counts as a gate problem or a screen-only failure.',
  '',
);
lines.push(...(missingCount ? [...missing.gates, ...missing.bots].map((f) => `- ${f}`) : ['None.']), '');
lines.push('## Gate problems at the gating sizes', '');
const gating = gates.filter((g) => g.gating);
const found = gating.flatMap((g) => g.problems.map((p) => `${g.scenario} @ ${g.viewport}: ${p}`));
lines.push(...(found.length ? found.map((p) => `- ${p}`) : ['None.']), '');
const problems = [...found, ...missing.gates.map((f) => `${f}: no result file`)];
lines.push('## Measured-only sizes', '');
const measured = gates.filter((g) => !g.gating).flatMap((g) => g.problems.map((p) => `${g.scenario} @ ${g.viewport}: ${p}`));
lines.push(...(measured.length ? [...new Set(measured)].map((p) => `- ${p}`) : ['None.']), '');
lines.push('## Screen-only user', '');
for (const b of [...bots].sort((a, c) => `${a.scenario}${a.viewport}${a.mode}`.localeCompare(`${c.scenario}${c.viewport}${c.mode}`))) {
  const flags = [b.done ? 'done' : 'NOT DONE', b.completion_miss ? 'completion_miss' : '', b.false_complete ? 'false_complete' : ''].filter(Boolean);
  lines.push(`- ${b.scenario} @ ${b.viewport} by ${b.mode}: ${flags.join(', ')}; ${b.actions} actions, ${b.looks} looks, ${b.keyboard_tabs} tabs${b.notes.length ? `; ${b.notes.join('; ')}` : ''}`);
}
lines.push('', `## Metrics at ${RATCHET_VIEWPORT} (lower is better)`, '');
lines.push('| scenario | key | now | baseline | last round |', '|---|---|---|---|---|');
for (const [sc, keys] of Object.entries(now).sort()) {
  for (const [k, v] of Object.entries(keys).sort()) {
    const b = base?.scenarios[sc]?.[k]?.value;
    const p = prev?.[sc]?.[k] ?? prev?.[sc]?.[BEFORE_R11[k]];
    lines.push(`| ${sc} | ${k} | ${v} | ${b ?? '–'} | ${p ?? '–'} |`);
  }
}
// What `node ux/ratchet.ts --round` compares: every key, the host-dependent ones included. main's
// baseline is the counterpart of ux/baseline.json only.
const ratchet = compare(
  base ?? { about: '', tolerances: {}, scenarios: {} }, now, process.env.UX_BASELINE ? undefined : mainBaseline(here, 'ui/ux/baseline.json'),
).failures;
lines.push('', '## Round ratchet', '', '`node ux/ratchet.ts --round`, the last command of the round task, fails on each line below.', '');
lines.push(...(ratchet.length ? ratchet.map((f) => `- ${f}`) : ['At or better than the baseline.']));
lines.push('', '## Not measured this round', '');
lines.push('- L4 keyed replay, L5 discoverability probe, L6 people: not run (no recorded sessions; operator-only).');
lines.push('- Questionnaire: no person ran the cards; the screen-only user replaced them.');
lines.push('');

const shots = join(out, 'gates', 'shots');
const kept: string[] = [];
if (existsSync(shots)) {
  for (const f of readdirSync(shots).filter((f) => f.includes(`@${RATCHET_VIEWPORT}-`)).sort()) {
    copyFileSync(join(shots, f), join(dir, 'shots', f));
    kept.push(f);
  }
  // The contact sheet is committed: quantise it when pngquant is installed (about 2.5 times smaller).
  const pngs = kept.map((f) => join(dir, 'shots', f));
  if (pngs.length) spawnSync('pngquant', ['--quality=60-85', '--force', '--skip-if-larger', '--ext', '.png', ...pngs], { stdio: 'ignore' });
}
lines.push('## Contact sheet', '', ...kept.map((f) => `- [${f}](shots/${f})`), '');
writeFileSync(join(dir, 'report.md'), lines.join('\n'));
const sum = (k: string): number => Object.values(now).reduce((a, m) => a + (m[k] ?? 0), 0);
const lost = (mode: string): number => missing.bots.filter((f) => f.endsWith(`-${mode}.json`)).length;
const counts = {
  gate_problems: problems.length,
  screen_only_failures: sum('screen_only.failed') + lost('pointer'),
  keyboard_failures: sum('screen_only.keyboard_failed') + lost('keyboard'),
};
writeFileSync(join(dir, 'round.json'), JSON.stringify({ id, metrics: now, problems, missing, trend: counts, ratchet, bots }, null, 2) + '\n');

const trend = join(roundsDir, 'trend.md');
const head = '# UX trend\n\n| round | gate problems | screen-only failures | keyboard failures |\n|---|---|---|---|\n';
const row = `| ${id} | ${counts.gate_problems} | ${counts.screen_only_failures} | ${counts.keyboard_failures} |\n`;
const old = existsSync(trend) ? readFileSync(trend, 'utf8').split('\n').filter((l) => !l.startsWith(`| ${id} |`)).join('\n') : head;
writeFileSync(trend, (old.endsWith('\n') ? old : old + '\n') + row);
console.log(
  `${id}: ${problems.length} gate problems, ${bots.filter((b) => !b.done).length} screen-only tasks not done, ` +
    `${missingCount} result files missing, ${ratchet.length} round ratchet lines; ${join(dir, 'report.md')}`,
);
process.exit(missingCount ? 1 : 0);
