//! A synced source whose content changed is never taken as built on the
//! node. cargo decides by modification time: a file synced with the time it
//! had on the caller's machine can be older than a build the node already
//! made from its old content, and a target directory seeded from a sibling
//! worktree carries that sibling's times.

use std::os::unix::fs::MetadataExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};
use std::time::{Duration, Instant, SystemTime};

use serde_json::Value;

use super::{Daemon, SLOT, forced_ssh, git, write_at};

const ONE: &str = "pub fn name() -> &'static str {\n    \"one\"\n}\n";
const TWO: &str = "pub fn name() -> &'static str {\n    \"two\"\n}\n";

/// A cargo workspace of two crates, `model` and `app` (a binary that prints
/// `model::name()`), in a repository with an `origin`, and a second
/// worktree of it at the same commit.
fn workspace(root: &Path) -> (PathBuf, PathBuf) {
    let a = root.join("a");
    let b = root.join("b");
    for c in ["model", "app"] {
        std::fs::create_dir_all(a.join(c).join("src")).unwrap();
    }
    let files = [
        (
            "Cargo.toml",
            "[workspace]\nmembers = [\"model\", \"app\"]\nresolver = \"2\"\n",
        ),
        (
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"model\",\n]\n\n[[package]]\nname = \"model\"\nversion = \"0.1.0\"\n",
        ),
        (
            "model/Cargo.toml",
            "[package]\nname = \"model\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        ),
        ("model/src/lib.rs", ONE),
        (
            "app/Cargo.toml",
            "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\nmodel = { path = \"../model\" }\n",
        ),
        (
            "app/src/main.rs",
            "fn main() {\n    println!(\"{}\", model::name());\n}\n",
        ),
        (".gitignore", "/target/\n"),
    ];
    for (path, body) in files {
        std::fs::write(a.join(path), body).unwrap();
    }
    git(&a, &["init", "-q"]);
    git(
        &a,
        &["remote", "add", "origin", "git@example.invalid:o/w.git"],
    );
    git(&a, &["add", "."]);
    git(&a, &["commit", "-qm", "workspace"]);
    git(
        &a,
        &["worktree", "add", "-q", "--detach", b.to_str().unwrap()],
    );
    (a, b)
}

/// `cargo run -p app` in `cwd`, synced to the stand-in node (not same-path).
fn run_app(d: &Daemon, ssh: &Path, cwd: &Path) -> Output {
    Command::new(SLOT)
        .args([env!("CARGO"), "run", "-p", "app"])
        .current_dir(cwd)
        .env("SLOT_HOST", "node")
        .env("SLOT_SSH", ssh)
        .env("SLOT_WSROOT", d.dir.path().join("state/ws"))
        .env("SLOT_REMOTE", SLOT)
        .env("SLOT_SOCKET", d.socket())
        .env("SLOT_SYNC_STALL", "20s")
        .env("SLOT_SYNC_LIMIT", "50s")
        .env("SLOT_UPLOAD_SLOTS", "0")
        .env("SLOT_UPLOAD_BWLIMIT", "0")
        .env("SLOT_CLUSTER_FILE", "off")
        .env("XDG_CONFIG_HOME", d.dir.path().join("config"))
        .env_remove("SLOT_JOB")
        .env_remove("SLOT_REMOTE_SAME_PATH")
        .env_remove("CARGO_TARGET_DIR")
        .env_remove("CARGO_BUILD_TARGET")
        .env_remove("CARGO_NET_OFFLINE")
        .env("CARGO_TERM_COLOR", "never")
        .stdin(Stdio::null())
        .output()
        .unwrap()
}

/// The directories in `dir` whose names do not start with `.`.
fn ids(dir: &Path) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir)
        .unwrap()
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| !n.starts_with('.'))
        .collect();
    v.sort();
    v
}

/// Every (device, inode) of the regular files under `dir`.
fn inodes(dir: &Path) -> Vec<(u64, u64)> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for e in std::fs::read_dir(&d).unwrap().flatten() {
            let m = e.path().symlink_metadata().unwrap();
            if m.is_dir() {
                stack.push(e.path());
            } else if m.is_file() {
                out.push((m.dev(), m.ino()));
            }
        }
    }
    out
}

fn mtime(p: &Path) -> SystemTime {
    std::fs::metadata(p).unwrap().modified().unwrap()
}

/// The node's own copy of `rel` in the one source mirror under the
/// workspace root.
fn on_node(d: &Daemon, rel: &str) -> PathBuf {
    let ws = d.dir.path().join("state/ws");
    let ids = ids(&ws);
    assert_eq!(ids.len(), 1, "{ids:?}");
    ws.join(&ids[0]).join(rel)
}

/// The defect seen on a node: an edit made before a build the node ran on
/// the old content reached the node after it, with the caller's older time.
/// cargo took the build as fresh and ran the old code.
#[test]
fn a_change_synced_after_a_build_of_the_old_content_is_compiled() {
    let t0 = Instant::now();
    let d = Daemon::start();
    let t = tempfile::tempdir().unwrap();
    let (a, _) = workspace(t.path());
    let ssh = forced_ssh(t.path(), &d, "");
    let first = run_app(&d, &ssh, &a);
    let err = String::from_utf8_lossy(&first.stderr);
    assert_eq!(first.status.code(), Some(0), "{err}");
    assert_eq!(String::from_utf8_lossy(&first.stdout), "one\n", "{err}");

    let edited = SystemTime::now() - Duration::from_secs(3600);
    write_at(&a.join("model/src/lib.rs"), TWO, edited);
    let second = run_app(&d, &ssh, &a);
    let err = String::from_utf8_lossy(&second.stderr);
    assert_eq!(second.status.code(), Some(0), "{err}");
    assert!(err.contains("Compiling model"), "{err}");
    assert_eq!(
        String::from_utf8_lossy(&second.stdout),
        "two\n",
        "the node ran the old build: {err}"
    );
    eprintln!("took {:?}", t0.elapsed());
}

/// What the sync leaves on the node: a file whose content changed has the
/// node's time of the sync, not the caller's; a file whose content did not
/// change keeps the node's time, so a `touch` on the node outlives the next
/// sync.
#[test]
fn a_synced_file_has_the_nodes_time_and_keeps_it_while_unchanged() {
    let d = Daemon::start();
    let t = tempfile::tempdir().unwrap();
    let (a, _) = workspace(t.path());
    let ssh = forced_ssh(t.path(), &d, "");
    let cat = |cwd: &Path| super::remote_call(&d, &ssh, cwd, &["cat", "model/src/lib.rs"]);
    let out = cat(&a);
    assert_eq!(out.status.code(), Some(0));

    let edited = SystemTime::now() - Duration::from_secs(3600);
    write_at(&a.join("model/src/lib.rs"), TWO, edited);
    let before = SystemTime::now() - Duration::from_secs(1);
    let out = cat(&a);
    let err = String::from_utf8_lossy(&out.stderr);
    assert_eq!(String::from_utf8_lossy(&out.stdout), TWO, "{err}");
    let node = on_node(&d, "model/src/lib.rs");
    assert!(
        mtime(&node) >= before,
        "a changed file has the caller's time on the node: {:?}",
        mtime(&node)
    );

    // A touch on the node, then a sync of the same content.
    let touched = SystemTime::now() + Duration::from_secs(60);
    std::fs::File::options()
        .write(true)
        .open(&node)
        .unwrap()
        .set_modified(touched)
        .unwrap();
    let out = cat(&a);
    assert_eq!(out.status.code(), Some(0));
    assert_eq!(mtime(&node), touched, "the sync undid the node's touch");
}

/// Two worktrees of one repository. The second changes a crate's source
/// before the first builds, and its first job is seeded from the first's
/// target directory after its sync: it compiles the changed crate.
#[test]
fn a_target_seeded_from_a_sibling_never_makes_a_changed_source_look_built() {
    let t0 = Instant::now();
    let d = Daemon::start_with(&["--seed-copy".as_ref(), "copy".as_ref()]);
    let t = tempfile::tempdir().unwrap();
    let (a, b) = workspace(t.path());
    let ssh = forced_ssh(t.path(), &d, "");
    let edited = SystemTime::now() - Duration::from_secs(3600);
    write_at(&b.join("model/src/lib.rs"), TWO, edited);

    let first = run_app(&d, &ssh, &a);
    let err = String::from_utf8_lossy(&first.stderr);
    assert_eq!(first.status.code(), Some(0), "{err}");
    assert_eq!(String::from_utf8_lossy(&first.stdout), "one\n", "{err}");
    let targets = d.dir.path().join("state/cache/target");
    let sibling = ids(&targets);
    assert_eq!(sibling.len(), 1, "{sibling:?}");
    let sibling = &sibling[0];

    let second = run_app(&d, &ssh, &b);
    let err = String::from_utf8_lossy(&second.stderr);
    assert_eq!(second.status.code(), Some(0), "{err}");
    assert!(
        err.contains(&format!("seeded from workspace {sibling}")),
        "not seeded: {err}"
    );
    assert!(
        err.contains("; 1 source file(s) differ from its sources"),
        "only the changed file is newer than the copy: {err}"
    );
    assert!(err.contains("Compiling model"), "{err}");
    assert_eq!(
        String::from_utf8_lossy(&second.stdout),
        "two\n",
        "the sibling's build of the old source ran: {err}"
    );

    let mine: Vec<String> = ids(&targets).into_iter().filter(|i| i != sibling).collect();
    assert_eq!(mine.len(), 1, "{mine:?}");
    let theirs = inodes(&targets.join(sibling));
    let shared: Vec<_> = inodes(&targets.join(&mine[0]))
        .into_iter()
        .filter(|i| theirs.contains(i))
        .collect();
    assert!(shared.is_empty(), "hard links into the sibling: {shared:?}");

    let log = std::fs::read_to_string(d.dir.path().join("state/jobs.jsonl")).unwrap();
    let jobs: Vec<Value> = log
        .lines()
        .map(|l| serde_json::from_str::<Value>(l).unwrap())
        .filter(|l| l.get("argv").is_some())
        .collect();
    assert_eq!(jobs.len(), 2, "{log}");
    assert_eq!(jobs[1]["seeded_from"], sibling.as_str(), "{}", jobs[1]);
    eprintln!("took {:?}", t0.elapsed());
}
