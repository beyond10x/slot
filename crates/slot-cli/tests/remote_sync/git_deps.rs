//! The git dependencies a checkout's `Cargo.lock` names reach the node with
//! the job: the client brings each locked revision into this machine's
//! cargo git database and copies those database entries to the node's, so
//! a build on a node without a way to the source (no network to a private
//! forge, no credential) still finds it. A source on a deny list keeps the
//! job here. The forge is a bare repository on this machine; the node is
//! [`forced_ssh`] with a cargo home of its own, offline.

use std::ffi::OsStr;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;

use super::{Daemon, forced_ssh, git, remote_call_env};

/// A bare repository `<root>/forge/dep.git` holding crate `dep`, whose
/// `n()` is 7; its URL and the commit id of its head.
fn forge(root: &Path) -> (String, String) {
    let work = root.join("forge-work");
    std::fs::create_dir_all(work.join("src")).unwrap();
    std::fs::write(
        work.join("Cargo.toml"),
        "[package]\nname = \"dep\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    std::fs::write(work.join("src/lib.rs"), "pub fn n() -> u32 {\n    7\n}\n").unwrap();
    git(&work, &["init", "-q"]);
    git(&work, &["add", "."]);
    git(&work, &["commit", "-qm", "dep"]);
    let bare = root.join("forge/dep.git");
    std::fs::create_dir_all(root.join("forge")).unwrap();
    git(
        root,
        &[
            "clone",
            "-q",
            "--bare",
            work.to_str().unwrap(),
            bare.to_str().unwrap(),
        ],
    );
    let rev = Command::new("git")
        .arg("-C")
        .arg(&bare)
        .args(["rev-parse", "HEAD"])
        .output()
        .unwrap();
    let rev = String::from_utf8_lossy(&rev.stdout).trim().to_string();
    (format!("file://{}", bare.display()), rev)
}

/// A package `app` in a git repository whose `Cargo.lock` takes `dep` from
/// `url` at `rev`; it prints `dep says <n>`.
fn app(root: &Path, url: &str, rev: &str) -> PathBuf {
    let r = root.join("app");
    std::fs::create_dir_all(r.join("src")).unwrap();
    std::fs::write(
        r.join("Cargo.toml"),
        format!(
            "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\ndep = {{ git = \"{url}\" }}\n\n[workspace]\n"
        ),
    )
    .unwrap();
    std::fs::write(
        r.join("Cargo.lock"),
        format!(
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"dep\",\n]\n\n[[package]]\nname = \"dep\"\nversion = \"0.1.0\"\nsource = \"git+{url}#{rev}\"\n"
        ),
    )
    .unwrap();
    std::fs::write(
        r.join("src/main.rs"),
        "fn main() {\n    println!(\"dep says {}\", dep::n());\n}\n",
    )
    .unwrap();
    std::fs::write(r.join(".gitignore"), "/target/\n").unwrap();
    git(&r, &["init", "-q"]);
    git(&r, &["add", "."]);
    git(&r, &["commit", "-qm", "app"]);
    r
}

/// The entries of the cargo git database under `cargo_home`.
fn db_entries(cargo_home: &Path) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(cargo_home.join("git/db"))
        .map(|rd| {
            rd.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// rsync calls of the stand-in node's ssh log that wrote into its cargo git
/// database.
fn db_copies(root: &Path) -> usize {
    std::fs::read_to_string(root.join("ssh.log"))
        .unwrap_or_default()
        .lines()
        .filter(|l| l.starts_with("rsync ") && l.contains("/git/db/"))
        .count()
}

/// A checkout whose `Cargo.lock` names a git source only this machine
/// reaches builds on a node that has no network to it; a second job copies
/// nothing.
#[test]
fn a_git_dependency_only_this_machine_reaches_builds_on_the_node() {
    let t0 = Instant::now();
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let (url, rev) = forge(&root);
    let repo = app(&root, &url, &rev);
    let here_home = root.join("cargo-here");
    let node_home = root.join("cargo-node");
    // The node is offline: cargo there reaches no git source.
    let d = Daemon::start_env(
        &[],
        &[
            ("CARGO_HOME", node_home.as_os_str()),
            ("CARGO_NET_OFFLINE", OsStr::new("true")),
        ],
    );
    let ssh = forced_ssh(
        &root,
        &d,
        &format!("export CARGO_HOME={}", node_home.display()),
    );
    // A wrapper's inner cargo: the node's fetch-once does not run for it.
    let argv = ["sh", "-c", "exec \"$0\" run -q", env!("CARGO")];
    let env = [("CARGO_HOME", here_home.to_str().unwrap())];
    let out = remote_call_env(&d, &ssh, &repo, &argv, &env);
    let err = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "{err}");
    assert_eq!(
        String::from_utf8_lossy(&out.stdout),
        "dep says 7\n",
        "{err}"
    );
    let here = db_entries(&here_home);
    assert_eq!(here.len(), 1, "fetched here: {here:?}");
    assert!(here[0].starts_with("dep-"), "{here:?}");
    assert_eq!(db_entries(&node_home), here, "the same entry on the node");
    assert!(
        err.lines()
            .any(|l| l.starts_with("slot: git dependencies: 1 copied to node")),
        "{err}"
    );
    assert_eq!(db_copies(&root), 1, "{err}");

    let again = remote_call_env(&d, &ssh, &repo, &argv, &env);
    let err = String::from_utf8_lossy(&again.stderr);
    assert_eq!(again.status.code(), Some(0), "{err}");
    assert!(!err.contains("slot: git dependencies:"), "{err}");
    assert_eq!(db_copies(&root), 1, "nothing copied a second time: {err}");
    eprintln!("took {:.1} s", t0.elapsed().as_secs_f64());
}

/// A git source on a deny list keeps the job on this machine, with the
/// source as its reason: a `git+file` path under a path line of
/// `remote-deny`, and a URL an `origin:` pattern matches, whether the
/// pattern is in `remote-deny` or in `remote-deny-origins`.
#[test]
fn a_denied_git_dependency_keeps_the_job_here() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let rev = "0123456789abcdef0123456789abcdef01234567";
    let d = Daemon::start();
    let config = d.dir.path().join("config/slot");
    std::fs::create_dir_all(&config).unwrap();
    std::fs::write(
        config.join("remote-deny"),
        format!(
            "{}\norigin:*git.example.org[:/]team/*\n",
            root.join("forge").display()
        ),
    )
    .unwrap();
    std::fs::write(
        config.join("remote-deny-origins"),
        "origin:https://other.example.org/*\n",
    )
    .unwrap();
    let file_url = format!("file://{}", root.join("forge/dep.git").display());
    let cases = [
        (file_url.clone(), "file"),
        (
            "https://git.example.org/team/dep.git?branch=main".to_string(),
            "origin-in-remote-deny",
        ),
        (
            "https://other.example.org/x/dep.git".to_string(),
            "origin-in-remote-deny-origins",
        ),
    ];
    for (url, name) in &cases {
        let case = root.join(name);
        std::fs::create_dir_all(&case).unwrap();
        let repo = app(&case, url, rev);
        let ssh = forced_ssh(&case, &d, "");
        let argv = ["echo", name];
        let out = remote_call_env(&d, &ssh, &repo, &argv, &[]);
        let err = String::from_utf8_lossy(&out.stderr);
        assert_eq!(out.status.code(), Some(0), "{err}");
        assert!(
            !err.contains("skipped"),
            "an origin: line is no tree: {err}"
        );
        assert_eq!(String::from_utf8_lossy(&out.stdout), format!("{name}\n"));
        let reason = format!("git dependency denied: git+{url}");
        assert!(
            err.contains(&format!(
                "slot: {reason}: the tree is not synced to node; running on this machine"
            )),
            "{err}"
        );
        assert_eq!(
            std::fs::read_to_string(case.join("ssh.log")).unwrap_or_default(),
            "",
            "ssh ran"
        );
        let want = super::super::serde_like(&argv);
        assert!(super::super::wait_for(|| d.logged(&argv) == 1));
        let line = std::fs::read_to_string(d.dir.path().join("state/jobs.jsonl"))
            .unwrap()
            .lines()
            .find(|l| l.contains(&want))
            .unwrap()
            .to_string();
        assert!(
            line.contains(&format!("\"local_reason\":\"{reason}\"")),
            "{line}"
        );
    }
}
