//! The git dependencies a checkout's `Cargo.lock` names reach the node with
//! the job: the client brings each locked revision into this machine's
//! cargo git database and copies those database entries to the node's, so
//! a build on a node without a way to the source (no network to a private
//! forge, no credential) still finds it. A source on a deny list keeps the
//! job here. The forge is a bare repository on this machine; the node is
//! [`forced_ssh`] with a cargo home of its own, offline.

use std::ffi::OsStr;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;

use super::{Daemon, SLOT, forced_ssh, git, remote_call_env};

/// A bare repository `<root>/forge/dep.git` holding crate `dep`, whose
/// `n()` is 7; its URL and the commit id of its head.
fn forge(root: &Path) -> (String, String) {
    let work = root.join("forge-work");
    std::fs::create_dir_all(work.join("src")).unwrap();
    std::fs::write(
        work.join("Cargo.toml"),
        "[package]\nname = \"dep\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    std::fs::write(work.join("src/lib.rs"), "pub fn n() -> u32 {\n    7\n}\n").unwrap();
    git(&work, &["init", "-q"]);
    git(&work, &["add", "."]);
    git(&work, &["commit", "-qm", "dep"]);
    let bare = root.join("forge/dep.git");
    std::fs::create_dir_all(root.join("forge")).unwrap();
    git(
        root,
        &[
            "clone",
            "-q",
            "--bare",
            work.to_str().unwrap(),
            bare.to_str().unwrap(),
        ],
    );
    let rev = Command::new("git")
        .arg("-C")
        .arg(&bare)
        .args(["rev-parse", "HEAD"])
        .output()
        .unwrap();
    let rev = String::from_utf8_lossy(&rev.stdout).trim().to_string();
    (format!("file://{}", bare.display()), rev)
}

/// A package `app` in a git repository whose `Cargo.lock` takes `dep` from
/// `url` at `rev`; it prints `dep says <n>`.
fn app(root: &Path, url: &str, rev: &str) -> PathBuf {
    let r = root.join("app");
    std::fs::create_dir_all(r.join("src")).unwrap();
    std::fs::write(
        r.join("Cargo.toml"),
        format!(
            "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\ndep = {{ git = \"{url}\" }}\n\n[workspace]\n"
        ),
    )
    .unwrap();
    std::fs::write(
        r.join("Cargo.lock"),
        format!(
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"dep\",\n]\n\n[[package]]\nname = \"dep\"\nversion = \"0.1.0\"\nsource = \"git+{url}#{rev}\"\n"
        ),
    )
    .unwrap();
    std::fs::write(
        r.join("src/main.rs"),
        "fn main() {\n    println!(\"dep says {}\", dep::n());\n}\n",
    )
    .unwrap();
    std::fs::write(r.join(".gitignore"), "/target/\n").unwrap();
    git(&r, &["init", "-q"]);
    git(&r, &["add", "."]);
    git(&r, &["commit", "-qm", "app"]);
    r
}

/// The entries of the cargo git database under `cargo_home`.
fn db_entries(cargo_home: &Path) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(cargo_home.join("git/db"))
        .map(|rd| {
            rd.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// rsync calls of the stand-in node's ssh log that wrote into its cargo git
/// database.
fn db_copies(root: &Path) -> usize {
    std::fs::read_to_string(root.join("ssh.log"))
        .unwrap_or_default()
        .lines()
        .filter(|l| l.starts_with("rsync ") && l.contains("/git/db/"))
        .count()
}

/// The stand-in node of these tests.
struct Node {
    d: Daemon,
    ssh: PathBuf,
    /// The cargo home its jobs use: `<root>/node-home/.cargo`.
    cargo_home: PathBuf,
}

/// A node whose daemon runs jobs offline with the cargo home
/// `<root>/node-home/.cargo`, reached through an ssh whose `slot shell` has
/// `HOME=<root>/node-home` and a `CARGO_HOME` the session chose
/// (`<root>/session-chosen`, which the shell must not take). `before(d)`
/// is shell code the ssh runs first.
fn node(root: &Path, before: impl Fn(&Daemon) -> String) -> Node {
    let home = root.join("node-home");
    std::fs::create_dir_all(&home).unwrap();
    let cargo_home = home.join(".cargo");
    let d = Daemon::start_env(
        &[],
        &[
            ("CARGO_HOME", cargo_home.as_os_str()),
            ("CARGO_NET_OFFLINE", OsStr::new("true")),
        ],
    );
    let ssh = forced_ssh(
        root,
        &d,
        &format!(
            "export HOME={}\nexport CARGO_HOME={}\n{}",
            home.display(),
            root.join("session-chosen").display(),
            before(&d)
        ),
    );
    Node { d, ssh, cargo_home }
}

/// Writes `text` to the client's slot configuration file `name`.
fn config(d: &Daemon, name: &str, text: &str) {
    let dir = d.dir.path().join("config/slot");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join(name), text).unwrap();
}

/// `cargo fetch` in `dir` with the cargo home `home`, as a build on this
/// machine leaves it.
fn fetch_here(dir: &Path, home: &Path) {
    let out = Command::new(env!("CARGO"))
        .arg("fetch")
        .current_dir(dir)
        .env("CARGO_HOME", home)
        .env("SLOT_SHIM_OFF", "1")
        .env_remove("CARGO_NET_OFFLINE")
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

/// Every file under `dir`, relative, sorted.
fn files_under(dir: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(p) = stack.pop() {
        for e in std::fs::read_dir(&p).into_iter().flatten().flatten() {
            let path = e.path();
            if e.file_type().is_ok_and(|t| t.is_dir()) {
                stack.push(path);
            } else {
                out.push(path.strip_prefix(dir).unwrap().display().to_string());
            }
        }
    }
    out.sort();
    out
}

/// A checkout whose `Cargo.lock` names a git source only this machine
/// reaches builds on a node that has no network to it; a second job copies
/// nothing.
#[test]
fn a_git_dependency_only_this_machine_reaches_builds_on_the_node() {
    let t0 = Instant::now();
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let (url, rev) = forge(&root);
    let repo = app(&root, &url, &rev);
    let here_home = root.join("cargo-here");
    let Node {
        d,
        ssh,
        cargo_home: node_home,
    } = node(&root, |_| String::new());
    // A wrapper's inner cargo: the node's fetch-once does not run for it.
    let argv = ["sh", "-c", "exec \"$0\" run -q", env!("CARGO")];
    let env = [("CARGO_HOME", here_home.to_str().unwrap())];
    let out = remote_call_env(&d, &ssh, &repo, &argv, &env);
    let err = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "{err}");
    assert_eq!(
        String::from_utf8_lossy(&out.stdout),
        "dep says 7\n",
        "{err}"
    );
    let here = db_entries(&here_home);
    assert_eq!(here.len(), 1, "fetched here: {here:?}");
    assert!(here[0].starts_with("dep-"), "{here:?}");
    assert_eq!(db_entries(&node_home), here, "the same entry on the node");
    assert!(
        !root.join("session-chosen").exists(),
        "the shell took the session's CARGO_HOME"
    );
    assert!(
        err.lines()
            .any(|l| l.starts_with("slot: git dependencies: 1 copied to node")),
        "{err}"
    );
    assert_eq!(db_copies(&root), 1, "{err}");

    let again = remote_call_env(&d, &ssh, &repo, &argv, &env);
    let err = String::from_utf8_lossy(&again.stderr);
    assert_eq!(again.status.code(), Some(0), "{err}");
    assert!(!err.contains("slot: git dependencies:"), "{err}");
    assert_eq!(db_copies(&root), 1, "nothing copied a second time: {err}");
    eprintln!("took {:.1} s", t0.elapsed().as_secs_f64());
}

/// A git source on a deny list keeps the job on this machine, with the
/// source as its reason: a `git+file` path under a path line of
/// `remote-deny`, and a URL an `origin:` pattern matches, whether the
/// pattern is in `remote-deny` or in `remote-deny-origins`.
#[test]
fn a_denied_git_dependency_keeps_the_job_here() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let rev = "0123456789abcdef0123456789abcdef01234567";
    let d = Daemon::start();
    let config = d.dir.path().join("config/slot");
    std::fs::create_dir_all(&config).unwrap();
    std::fs::write(
        config.join("remote-deny"),
        format!(
            "{}\norigin:*git.example.org[:/]team/*\n",
            root.join("forge").display()
        ),
    )
    .unwrap();
    std::fs::write(
        config.join("remote-deny-origins"),
        "origin:https://other.example.org/*\n",
    )
    .unwrap();
    let file_url = format!("file://{}", root.join("forge/dep.git").display());
    let cases = [
        (file_url.clone(), "file"),
        (
            "https://git.example.org/team/dep.git?branch=main".to_string(),
            "origin-in-remote-deny",
        ),
        (
            "https://other.example.org/x/dep.git".to_string(),
            "origin-in-remote-deny-origins",
        ),
    ];
    for (url, name) in &cases {
        let case = root.join(name);
        std::fs::create_dir_all(&case).unwrap();
        let repo = app(&case, url, rev);
        let ssh = forced_ssh(&case, &d, "");
        let argv = ["echo", name];
        let out = remote_call_env(&d, &ssh, &repo, &argv, &[]);
        let err = String::from_utf8_lossy(&out.stderr);
        assert_eq!(out.status.code(), Some(0), "{err}");
        assert!(
            !err.contains("skipped"),
            "an origin: line is no tree: {err}"
        );
        assert_eq!(String::from_utf8_lossy(&out.stdout), format!("{name}\n"));
        let reason = format!("git dependency denied: git+{url}");
        assert!(
            err.contains(&format!(
                "slot: {reason}: the tree is not synced to node; running on this machine"
            )),
            "{err}"
        );
        assert_eq!(
            std::fs::read_to_string(case.join("ssh.log")).unwrap_or_default(),
            "",
            "ssh ran"
        );
        let want = super::super::serde_like(&argv);
        assert!(super::super::wait_for(|| d.logged(&argv) == 1));
        let line = std::fs::read_to_string(d.dir.path().join("state/jobs.jsonl"))
            .unwrap()
            .lines()
            .find(|l| l.contains(&want))
            .unwrap()
            .to_string();
        assert!(
            line.contains(&format!("\"local_reason\":\"{reason}\"")),
            "{line}"
        );
    }
}

/// The entries of both places a node's cargo git database could be: the
/// account's (`node-home/.cargo`) and the one a session's `CARGO_HOME`
/// would pick.
fn crossed(root: &Path, n: &Node) -> Vec<String> {
    let mut v = db_entries(&n.cargo_home);
    v.extend(db_entries(&root.join("session-chosen")));
    v
}

/// The cargo home of this machine as the client sees it.
fn here_env(home: &Path) -> [(&'static str, &str); 1] {
    [("CARGO_HOME", home.to_str().unwrap())]
}

/// A database entry is copied only when cargo maps the lock's own source
/// to it: an entry of a private fork with the same name that holds the same
/// commit stays here, and the lock's own source is fetched here.
#[test]
fn an_entry_of_another_url_with_the_same_name_and_commit_is_not_copied() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let (url, rev) = forge(&root);
    std::fs::create_dir_all(root.join("private")).unwrap();
    git(
        &root,
        &[
            "clone",
            "-q",
            "--bare",
            root.join("forge/dep.git").to_str().unwrap(),
            root.join("private/dep.git").to_str().unwrap(),
        ],
    );
    let here_home = root.join("cargo-here");
    let fork = app(
        &root.join("fork-user"),
        &format!("file://{}", root.join("private/dep.git").display()),
        &rev,
    );
    fetch_here(&fork, &here_home);
    let fork_entry = db_entries(&here_home);
    assert_eq!(fork_entry.len(), 1, "{fork_entry:?}");
    let repo = app(&root, &url, &rev);
    let n = node(&root, |_| String::new());
    config(
        &n.d,
        "remote-deny",
        &format!("{}\n", root.join("private").display()),
    );
    let out = remote_call_env(&n.d, &n.ssh, &repo, &["echo", "f1"], &here_env(&here_home));
    let err = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "{err}");
    assert_eq!(String::from_utf8_lossy(&out.stdout), "f1\n", "{err}");
    let crossed = crossed(&root, &n);
    assert!(
        !crossed.contains(&fork_entry[0]),
        "the fork's entry crossed: {crossed:?}: {err}"
    );
    assert_eq!(
        db_entries(&here_home).len(),
        2,
        "the lock's own entry: {err}"
    );
    assert_eq!(crossed.len(), 1, "{crossed:?}: {err}");
}

/// The node names the entries it lacks, but only entries the job asked for
/// cross: an answer that names another one sends nothing and the job runs
/// here.
#[test]
fn an_entry_the_node_names_unasked_is_not_sent() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let (url, rev) = forge(&root);
    let repo = app(&root, &url, &rev);
    let here_home = root.join("cargo-here");
    let evil = here_home.join("git/db/evil-00ff00ff00ff00ff");
    std::fs::create_dir_all(&evil).unwrap();
    git(&evil, &["init", "-q", "--bare"]);
    std::fs::write(evil.join("secret.txt"), "not for the node\n").unwrap();
    let n = node(&root, |d| {
        format!(
            "case \"$*\" in *__cargo-git*) SSH_ORIGINAL_COMMAND=\"$*\" {SLOT} shell --socket {} --state-dir {}; echo missing evil-00ff00ff00ff00ff; exit 0;; esac",
            d.socket().display(),
            d.dir.path().join("state").display()
        )
    });
    let out = remote_call_env(&n.d, &n.ssh, &repo, &["echo", "f2"], &here_env(&here_home));
    let err = String::from_utf8_lossy(&out.stderr);
    // A remote job that cannot start does not run here either.
    assert_eq!(out.status.code(), Some(3), "{err}");
    assert_eq!(String::from_utf8_lossy(&out.stdout), "", "{err}");
    assert!(err.contains("the job did not run"), "{err}");
    let crossed = crossed(&root, &n);
    assert!(
        !crossed.iter().any(|e| e.starts_with("evil-")),
        "{crossed:?}: {err}"
    );
    assert!(
        err.contains("slot: remote build on node did not start (")
            && err.contains("evil-00ff00ff00ff00ff"),
        "{err}"
    );
}

/// A source that git rewrites (`url.<base>.insteadOf`) to a denied origin
/// is denied: cargo would fetch from the rewritten URL.
