/// A checkout with a `Cargo.lock` at `<root>/<name>`.
fn checkout_with_lock(root: &Path, name: &str, lock: &str) -> PathBuf {
    let r = root.join(name);
    std::fs::create_dir_all(&r).unwrap();
    std::fs::write(
        r.join("Cargo.toml"),
        "[package]\nname = \"x\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::write(r.join("Cargo.lock"), lock).unwrap();
    git(&r, &["init", "-q"]);
    git(&r, &["add", "."]);
    git(&r, &["commit", "-qm", "x"]);
    r
}

/// With a deny list that names anything, a lock file the check cannot read
/// or a git source it cannot take apart keeps the job here.
#[test]
fn a_lock_file_the_check_cannot_read_keeps_the_job_here() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let n = node(&root, |_| String::new());
    config(
        &n.d,
        "remote-deny",
        &format!("{}\n", root.join("elsewhere").display()),
    );
    let pkg = |source: &str| {
        format!(
            "version = 3\n\n[[package]]\nname = \"d\"\nversion = \"0.1.0\"\nsource = \"{source}\"\n"
        )
    };
    let cases = [
        ("garbage", "[[package]\nname = ".to_string()),
        ("short-rev", pkg("git+file:///srv/x/dep.git#abc123")),
        ("no-rev", pkg("git+file:///srv/x/dep.git")),
        (
            "no-scheme",
            pkg("git+dep.git#0123456789abcdef0123456789abcdef01234567"),
        ),
    ];
    for (name, lock) in &cases {
        let repo = checkout_with_lock(&root, name, lock);
        let out = remote_call_env(&n.d, &n.ssh, &repo, &["echo", name], &[]);
        let err = String::from_utf8_lossy(&out.stderr);
        assert_eq!(out.status.code(), Some(0), "{name}: {err}");
        assert!(
            err.contains("slot: git dependency denied: "),
            "{name}: {err}"
        );
    }
    assert_eq!(
        std::fs::read_to_string(root.join("ssh.log")).unwrap_or_default(),
        "",
        "ssh ran"
    );
}

/// Only a git database's objects, refs and `HEAD` cross: not its `config`
/// (a URL with a login, an `http.extraHeader`), hooks, `info/` or
/// `FETCH_HEAD`.
#[test]
fn only_git_objects_and_refs_reach_the_node() {
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    let (url, rev) = forge(&root);
    let repo = app(&root, &url, &rev);
    let here_home = root.join("cargo-here");
    fetch_here(&repo, &here_home);
    let entries = db_entries(&here_home);
    assert_eq!(entries.len(), 1, "{entries:?}");
    let entry = here_home.join("git/db").join(&entries[0]);
    let mut config_text = std::fs::read_to_string(entry.join("config")).unwrap_or_default();
    config_text.push_str(
        "[http]\n\textraHeader = Authorization: Bearer s3cret-header\n[remote \"o\"]\n\turl = https://user:s3cret-token@git.example.org/team/dep.git\n",
    );
    std::fs::write(entry.join("config"), config_text).unwrap();
    std::fs::create_dir_all(entry.join("hooks")).unwrap();
    std::fs::write(
        entry.join("hooks/post-checkout"),
        "#!/bin/sh\necho s3cret-hook\n",
    )
    .unwrap();
    std::fs::create_dir_all(entry.join("info")).unwrap();
    std::fs::write(entry.join("info/attributes"), "* s3cret-attr\n").unwrap();
    std::fs::write(
        entry.join("FETCH_HEAD"),
        "x https://user:s3cret-fetch@h/r\n",
    )
    .unwrap();
    let n = node(&root, |_| String::new());
    let out = remote_call_env(
        &n.d,
        &n.ssh,
        &repo,
        &["echo", "inv6"],
        &here_env(&here_home),
    );
    let err = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "{err}");
    let node_entry = [
        n.cargo_home.join("git/db").join(&entries[0]),
        root.join("session-chosen/git/db").join(&entries[0]),
    ]
    .into_iter()
    .find(|p| p.is_dir())
    .unwrap_or_else(|| panic!("not copied: {err}"));
    let files = files_under(&node_entry);
    for f in &files {
        assert!(
            f == "HEAD"
                || f == "packed-refs"
                || f.starts_with("objects/")
                || f.starts_with("refs/"),
            "{f} crossed: {files:?}"
        );
        let body = std::fs::read(node_entry.join(f)).unwrap();
        assert!(
            !String::from_utf8_lossy(&body).contains("s3cret"),
            "{f} carries a secret"
        );
    }
    assert!(files.iter().any(|f| f.starts_with("objects/")), "{files:?}");
}
