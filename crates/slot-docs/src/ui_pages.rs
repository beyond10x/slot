/// The `as` values the component set draws.
const AS: &[&str] = &[
    "text",
    "number",
    "badge",
    "list",
    "map",
    "time",
    "timestamp",
    "duration",
    "bytes",
];

/// Generates every file from the document's and the binding's text.
pub fn generate(document: &str, binding: &str) -> Result<Files> {
    let doc: Doc = serde_yaml_ng::from_str(document).context("spec/ui/slot.ui.yaml")?;
    let binding: Binding = serde_yaml_ng::from_str(binding).context("spec/http.yaml")?;
    if doc.format != "ess-ui/1" {
        bail!("format: `{}` is not ess-ui/1", doc.format);
    }
    let views = views(&binding)?;
    let routes = doc
        .pages
        .iter()
        .map(|(name, page)| (name.clone(), route(name, page)))
        .collect::<BTreeMap<_, _>>();
    let mut hosts = BTreeSet::new();
    let mut read_views = BTreeSet::new();
    let mut files = Files::new();
    for (name, page) in &doc.pages {
        let vue = page_component(&doc, name, page, &routes, &mut hosts, &mut read_views)
            .with_context(|| format!("pages/{name}"))?;
        files.insert(format!("pages/{}.vue", pascal(name)), vue);
    }
    for view in &read_views {
        if !views.contains_key(view) {
            bail!("view `{view}` is read by a page and has no route in spec/http.yaml");
        }
    }
    if !doc.pages.contains_key(&doc.navigation.home) {
        bail!("navigation.home: `{}` names no page", doc.navigation.home);
    }
    files.insert("pages.ts".into(), pages_ts(&doc, &routes));
    files.insert(
        "ui.ts".into(),
        ui_ts(&doc, &routes, &views, &read_views, &hosts),
    );
    Ok(files)
}

/// A view's route: the path, relative to the page, and how the rows come back.
struct ViewRoute {
    path: String,
    params: Vec<(String, String)>,
    body: String,
}

fn views(binding: &Binding) -> Result<BTreeMap<String, ViewRoute>> {
    let mut out = BTreeMap::new();
    for r in &binding.routes {
        let Some(view) = &r.view else { continue };
        if r.method.as_deref().unwrap_or("get") != "get" {
            bail!("spec/http.yaml: view `{view}` is not read with get");
        }
        let Some(path) = &r.path else {
            bail!("spec/http.yaml: view `{view}` has no path");
        };
        let mut params = Vec::new();
        for (var, source) in &r.parameters {
            let Some(param) = source.strip_prefix("param.") else {
                bail!("spec/http.yaml: view `{view}`: parameter `{var}` is not a `param.`");
            };
            params.push((var.clone(), param.to_owned()));
        }
        let body = r.body.clone().unwrap_or_else(|| "rows".into());
        out.insert(
            view.clone(),
            ViewRoute {
                path: path.trim_start_matches('/').to_owned(),
                params,
                body,
            },
        );
    }
    Ok(out)
}

/// A page's route below `#/`: its name's segments without a closing `list`, a closing `detail`
/// replaced by its params.
fn route(name: &str, page: &Page) -> Vec<String> {
    let mut segs: Vec<String> = name.split('.').map(str::to_owned).collect();
    if segs.len() > 1 && segs.last().is_some_and(|s| s == "list") {
        segs.pop();
    }
    if !page.params.is_empty() && segs.len() > 1 && segs.last().is_some_and(|s| s == "detail") {
        segs.pop();
    }
    segs.extend(page.params.keys().map(|p| format!(":{p}")));
    segs
}

fn pascal(name: &str) -> String {
    name.split(['.', '_', '-'])
        .map(|s| {
            let mut c = s.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

/// A JavaScript string literal.
fn js(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

/// A duration (`2s`, `500ms`, `1m`) in milliseconds.
fn duration_ms(s: &str) -> Result<u64> {
    let (n, unit) = s
        .find(|c: char| !c.is_ascii_digit())
        .map(|i| s.split_at(i))
        .context("a duration names its unit")?;
    let n: u64 = n.parse().with_context(|| format!("duration `{s}`"))?;
    Ok(match unit {
        "ms" => n,
        "s" => n * 1000,
        "m" => n * 60_000,
        "h" => n * 3_600_000,
        _ => bail!("duration `{s}`: unit `{unit}`"),
    })
}

fn field_def(f: &Field) -> FieldDef {
    match f {
        Field::Name(n) => FieldDef {
            field: n.clone(),
            label: None,
            as_: None,
            unit: None,
            tone_by: None,
            host: None,
            reason: None,
            stands_in_for: None,
        },
        Field::Full(d) => FieldDef {
            field: d.field.clone(),
            label: d.label.clone(),
            as_: d.as_.clone(),
            unit: d.unit.clone(),
            tone_by: d.tone_by.clone(),
            host: d.host.clone(),
            reason: None,
            stands_in_for: None,
        },
    }
}

/// One field as the component set takes it: a `Column` of `ui/src/lib/spec.ts`.
fn column(doc: &Doc, f: &Field, hosts: &mut BTreeSet<String>) -> Result<String> {
    let d = field_def(f);
    let mut s = format!(
        "{{ field: {}, label: {}",
        js(&d.field),
        js(d.label.as_deref().unwrap_or(&d.field))
    );
    if let Some(a) = &d.as_ {
        if !AS.contains(&a.as_str()) {
            bail!(
                "field `{}`: `as: {a}` is not drawn by the component set",
                d.field
            );
        }
        let _ = write!(s, ", as: {}", js(a));
    }
    if let Some(u) = &d.unit {
        let _ = write!(s, ", unit: {}", js(u));
    }
    if let Some(t) = &d.tone_by {
        if !doc.tone_maps.contains_key(t) {
            bail!("field `{}`: tone map `{t}` is not declared", d.field);
        }
        let _ = write!(s, ", tones: toneMaps[{}]", js(t));
    }
    if let Some(h) = &d.host {
        if !hosts.insert(h.clone()) {
            bail!("host `{h}` is declared twice");
        }
        let _ = write!(s, ", host: {}", js(h));
    }
    s.push_str(" }");
    Ok(s)
}

/// A filter expression of `reads.filter` as a TypeScript expression over `row` and `state`.
fn filter_ts(expr: &str, state: &BTreeSet<String>) -> Result<String> {
    let tokens = lex(expr)?;
    let mut p = Parser {
        tokens,
        at: 0,
        state,
    };
    let out = p.or()?;
    if p.at != p.tokens.len() {
        bail!("filter `{expr}`: unexpected `{}`", p.tokens[p.at]);
    }
    Ok(out)
}

fn lex(s: &str) -> Result<Vec<String>> {
    let mut out = Vec::new();
    let b: Vec<char> = s.chars().collect();
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        if c.is_whitespace() {
            i += 1;
        } else if "[](),".contains(c) {
            out.push(c.to_string());
            i += 1;
        } else if (c == '=' || c == '!') && b.get(i + 1) == Some(&'=') {
            out.push(format!("{c}="));
            i += 2;
        } else if c == '\'' || c == '"' {
            let end = b[i + 1..]
                .iter()
                .position(|&x| x == c)
                .with_context(|| format!("filter `{s}`: an unclosed string"))?;
            out.push(b[i..=i + 1 + end].iter().collect());
            i += end + 2;
        } else {
            let start = i;
            while i < b.len() && !b[i].is_whitespace() && !"[](),=!".contains(b[i]) {
                i += 1;
            }
            if start == i {
                bail!("filter `{s}`: unexpected `{c}`");
            }
            out.push(b[start..i].iter().collect());
        }
    }
    Ok(out)
}

struct Parser<'a> {
    tokens: Vec<String>,
    at: usize,
    state: &'a BTreeSet<String>,
}

impl Parser<'_> {
    fn peek(&self) -> Option<&str> {
        self.tokens.get(self.at).map(String::as_str)
    }

    fn next(&mut self) -> Result<String> {
        let t = self
            .tokens
            .get(self.at)
            .cloned()
            .context("filter ends early")?;
        self.at += 1;
        Ok(t)
    }

    fn expect(&mut self, t: &str) -> Result<()> {
        let got = self.next()?;
        if got != t {
            bail!("filter: `{t}` expected, `{got}` found");
        }
        Ok(())
    }

    fn or(&mut self) -> Result<String> {
        let mut out = self.and()?;
        while self.peek() == Some("or") {
            self.at += 1;
            out = format!("{out} || {}", self.and()?);
        }
        Ok(out)
    }

    fn and(&mut self) -> Result<String> {
        let mut out = self.unary()?;
        while self.peek() == Some("and") {
            self.at += 1;
            out = format!("{out} && {}", self.unary()?);
        }
        Ok(out)
    }

    fn unary(&mut self) -> Result<String> {
        match self.peek() {
            Some("not") => {
                self.at += 1;
                Ok(format!("!({})", self.unary()?))
            }
            Some("(") => {
                self.at += 1;
                let inner = self.or()?;
                self.expect(")")?;
                Ok(format!("({inner})"))
            }
            _ => self.comparison(),
        }
    }

    fn comparison(&mut self) -> Result<String> {
        let left = self.operand()?;
        match self.next()?.as_str() {
            "==" => Ok(format!("eq({left}, {})", self.operand()?)),
            "!=" => Ok(format!("!eq({left}, {})", self.operand()?)),
            "contains" => Ok(format!("contains({left}, {})", self.operand()?)),
            "in" => {
                self.expect("[")?;
                let mut items = vec![self.operand()?];
                while self.peek() == Some(",") {
                    self.at += 1;
                    items.push(self.operand()?);
                }
                self.expect("]")?;
                Ok(format!("among({left}, [{}])", items.join(", ")))
            }
            op => bail!("filter: `{op}` is not a comparison"),
        }
    }

    fn operand(&mut self) -> Result<String> {
        let t = self.next()?;
        if let Some(f) = t.strip_prefix("row.") {
            return Ok(format!("row[{}]", js(f)));
        }
        if let Some(s) = t.strip_prefix("state.") {
            if !self.state.contains(s) {
                bail!("filter: `{t}` names no state of the page");
            }
            return Ok(format!("state[{}]", js(s)));
        }
        if let Some(p) = t.strip_prefix("params.") {
            return Ok(format!("params[{}]", js(p)));
        }
        if t.starts_with('\'') || t.starts_with('"') {
            return Ok(js(&t[1..t.len() - 1]));
        }
        if [
            "and", "or", "not", "in", "contains", "[", "]", "(", ")", ",",
        ]
        .contains(&t.as_str())
        {
            bail!("filter: a value expected, `{t}` found");
        }
        Ok(js(&t))
    }
}

/// An expression of a read's `params` (`params.<name>` or `state.<name>`, or a literal) in TypeScript.
fn value_ts(expr: &str) -> String {
    if let Some(p) = expr.strip_prefix("params.") {
        format!("props.params[{}]", js(p))
    } else if let Some(s) = expr.strip_prefix("state.") {
        format!("state[{}]", js(s))
    } else {
        js(expr)
    }
}

/// The navigation a `navigate` action makes, as a call of `go`, reading `row` where it names one.
fn navigate_ts(n: &Navigate, routes: &BTreeMap<String, Vec<String>>) -> Result<String> {
    if !routes.contains_key(&n.to) {
        bail!("navigate.to: `{}` names no page", n.to);
    }
    let params = n
        .params
        .iter()
        .map(|(k, v)| {
            let value = v
                .strip_prefix("row.")
                .map_or_else(|| value_ts(v), |f| format!("String(row[{}])", js(f)));
            format!("{}: {value}", js(k))
        })
        .collect::<Vec<_>>()
        .join(", ");
    Ok(format!("go({}, {{ {params} }})", js(&n.to)))
}

fn page_component(
    doc: &Doc,
    name: &str,
    page: &Page,
    routes: &BTreeMap<String, Vec<String>>,
    hosts: &mut BTreeSet<String>,
    read_views: &mut BTreeSet<String>,
) -> Result<String> {
    if !["list_page", "detail_page"].contains(&page.kind.as_str()) {
        bail!("kind `{}` is not generated", page.kind);
    }
    let state: BTreeSet<String> = page
        .state
        .iter()
        .filter_map(|(k, v)| v.as_ref().map(|d| (k, d)))
        .map(|(k, d)| {
            if d.ty != "string" {
                bail!("state `{k}`: only `string` state is generated");
            }
            if d.store.as_deref().is_some_and(|s| s != "url") {
                bail!("state `{k}`: only state in the url is generated");
            }
            Ok(k.clone())
        })
        .collect::<Result<_>>()?;
    let sections: Vec<&Section> = page.sections.iter().filter(|s| !s.remove).collect();
    let mut script = String::new();
    let mut body = String::new();
    let mut imports: BTreeSet<&str> = BTreeSet::new();
    let mut lib: BTreeSet<&str> = BTreeSet::new();
    imports.insert("SpecPage");
    let mut filters_markup = String::new();
    let mut section_markup: BTreeMap<String, String> = BTreeMap::new();
    let mut order = Vec::new();
    let mut header_reads: BTreeMap<String, String> = BTreeMap::new();

    if !state.is_empty() {
        lib.insert("useUrlState");
        let keys = state.iter().map(|k| js(k)).collect::<Vec<_>>().join(", ");
        let _ = writeln!(script, "const state = useUrlState([{keys}]);");
    }
    for s in &sections {
        let path = format!("pages/{name}/sections/{}", s.name);
        let id = s.name.replace('-', "_");
        order.push(s.name.clone());
        if let Some(host) = &s.host {
            if s.component.is_some() {
                bail!("section `{}`: a host slot carries no component", s.name);
            }
            if !hosts.insert(host.clone()) {
                bail!("host `{host}` is declared twice");
            }
            imports.insert("SpecHost");
            imports.insert("SpecSection");
            let title = s
                .title
                .as_deref()
                .map(|t| format!(" title=\"{}\"", attr(t)))
                .unwrap_or_default();
            section_markup.insert(
                s.name.clone(),
                format!(
                    "<SpecSection path=\"{path}\"{title}><SpecHost name=\"{host}\" :params=\"props.params\" /></SpecSection>"
                ),
            );
            continue;
        }
        let component = s
            .component
            .as_deref()
            .with_context(|| format!("section `{}` has no component", s.name))?;
        let reads = match (&s.reads, component) {
            (Some(r), "collection" | "record") => Some(r),
            (None, "filter_bar") => None,
            (_, c) => bail!(
                "section `{}`: component `{c}` with this read is not generated",
                s.name
            ),
        };
        if let Some(r) = reads {
            read_views.insert(r.view.clone());
            if r.paging
                .as_deref()
                .is_some_and(|p| p != "client" && p != "none")
            {
                bail!(
                    "section `{}`: paging `{}` is not generated",
                    s.name,
                    r.paging.as_deref().unwrap_or("")
                );
            }
            lib.insert("useView");
            let params = r
                .params
                .iter()
                .map(|(k, v)| format!("{}: {}", js(k), value_ts(v)))
                .collect::<Vec<_>>()
                .join(", ");
            let refresh = r
                .refresh
                .as_deref()
                .map(duration_ms)
                .transpose()?
                .unwrap_or(0);
            let _ = writeln!(
                script,
                "const read_{id} = useView({}, () => ({}), {refresh});",
                js(&r.view),
                if params.is_empty() {
                    "{}".to_owned()
                } else {
                    format!("{{ {params} }}")
                }
            );
            match &r.filter {
                Some(f) => {
                    lib.insert("eq");
                    lib.insert("among");
                    lib.insert("contains");
                    let _ = writeln!(
                        script,
                        "const rows_{id} = computed(() => read_{id}.rows.filter((row) => {}));",
                        filter_ts(f, &state).with_context(|| format!("section `{}`", s.name))?
                    );
                }
                None => {
                    let _ = writeln!(script, "const rows_{id} = computed(() => read_{id}.rows);");
                }
            }
            header_reads.insert(s.name.clone(), id.clone());
        }
        match component {
            "filter_bar" => {
                imports.insert("SpecFilterBar");
                let search = s.search.as_ref().map(|q| {
                    format!(
                        "{{ key: {}, placeholder: {} }}",
                        js(state_key(&q.binds)),
                        js(q.placeholder.as_deref().unwrap_or(""))
                    )
                });
                let choices = s
                    .choices
                    .iter()
                    .map(|c| {
                        if c.component != "choice" {
                            bail!("choice `{}`: component `{}`", c.name, c.component);
                        }
                        Ok(format!(
                            "{{ key: {}, label: {}, placeholder: {}, options: [{}] }}",
                            js(state_key(&c.binds)),
                            js(&c.name),
                            js(c.placeholder.as_deref().unwrap_or("")),
                            c.options
                                .iter()
                                .map(|o| js(o))
                                .collect::<Vec<_>>()
                                .join(", ")
                        ))
                    })
                    .collect::<Result<Vec<_>>>()?;
                let _ = writeln!(
                    script,
                    "const filters_{id}: FilterBar = {{ search: {}, choices: [{}] }};",
                    search.unwrap_or_else(|| "undefined".into()),
                    choices.join(", ")
                );
                lib.insert("type FilterBar");
                let markup = format!(
                    "<SpecFilterBar path=\"{path}\" :bar=\"filters_{id}\" :state=\"state\" />"
                );
                if page.header.as_ref().and_then(|h| h.filters.as_deref()) == Some(s.name.as_str())
                {
                    filters_markup = markup;
                } else {
                    section_markup.insert(s.name.clone(), markup);
                }
            }
            "collection" => {
                imports.insert("SpecTable");
                lib.insert("type Column");
                let cols = s
                    .columns
                    .iter()
                    .map(|c| column(doc, c, hosts))
                    .collect::<Result<Vec<_>>>()?;
                let _ = writeln!(
                    script,
                    "const columns_{id}: Column[] = [\n  {},\n];",
                    cols.join(",\n  ")
                );
                let key = s
                    .reads
                    .as_ref()
                    .and_then(|r| r.key.as_deref())
                    .unwrap_or("id");
                let open = match s.row_actions.as_slice() {
                    [] => String::new(),
                    [a] => {
                        lib.insert("go");
                        lib.insert("type Row");
                        let _ = writeln!(
                            script,
                            "function open_{id}(row: Row): void {{\n  {};\n}}",
                            navigate_ts(&a.navigate, routes)?
                        );
                        format!(
                            " open-label=\"{}\" @open=\"open_{id}\"",
                            attr(a.label.as_deref().unwrap_or(&a.name))
                        )
                    }
                    _ => bail!("section `{}`: one row action is generated", s.name),
                };
                let pager = s
                    .reads
                    .as_ref()
                    .and_then(|r| r.pager.as_ref())
                    .map(|p| {
                        format!(
                            " :sizes=\"[{}]\"",
                            p.sizes
                                .iter()
                                .map(u32::to_string)
                                .collect::<Vec<_>>()
                                .join(", ")
                        )
                    })
                    .unwrap_or_default();
                let empty = s
                    .states
                    .as_ref()
                    .and_then(|st| st.empty.as_ref())
                    .map(|e| format!(" empty=\"{}\"", attr(&e.message)))
                    .unwrap_or_default();
                let title = s
                    .title
                    .as_deref()
                    .map(|t| format!(" title=\"{}\"", attr(t)))
                    .unwrap_or_default();
                section_markup.insert(
                    s.name.clone(),
                    format!(
                        "<SpecTable path=\"{path}\"{title} :columns=\"columns_{id}\" :rows=\"rows_{id}\" :status=\"read_{id}.status\" row-key=\"{key}\"{empty}{pager}{open} />"
                    ),
                );
            }
            "record" => {
                imports.insert("SpecRecord");
                lib.insert("type Column");
                lib.insert("type FieldGroup");
                let fields = s
                    .fields
                    .iter()
                    .map(|c| column(doc, c, hosts))
                    .collect::<Result<Vec<_>>>()?;
                let groups = s
                    .groups
                    .iter()
                    .map(|g| {
                        let fs = g
                            .fields
                            .iter()
                            .map(|c| column(doc, c, hosts))
                            .collect::<Result<Vec<_>>>()?;
                        Ok(format!(
                            "{{ name: {}, label: {}, collapsed: {}, fields: [\n    {},\n  ] }}",
                            js(&g.name),
                            js(g.label.as_deref().unwrap_or(&g.name)),
                            g.collapsed,
                            fs.join(",\n    ")
                        ))
                    })
                    .collect::<Result<Vec<_>>>()?;
                let _ = writeln!(
                    script,
                    "const fields_{id}: Column[] = [\n  {},\n];",
                    fields.join(",\n  ")
                );
                let _ = writeln!(
                    script,
                    "const groups_{id}: FieldGroup[] = [\n  {},\n];",
                    groups.join(",\n  ")
                );
                let title = s
                    .title
                    .as_deref()
                    .map(|t| format!(" title=\"{}\"", attr(t)))
                    .unwrap_or_default();
                section_markup.insert(
                    s.name.clone(),
                    format!(
                        "<SpecRecord path=\"{path}\"{title} :row=\"rows_{id}[0]\" :status=\"read_{id}.status\" :fields=\"fields_{id}\" :groups=\"groups_{id}\" />"
                    ),
                );
            }
            c => bail!("section `{}`: component `{c}` is not generated", s.name),
        }
    }

    // The header.
    let header = page.header.as_ref();
    let title = header
        .and_then(|h| h.title.as_deref())
        .filter(|t| *t != "from_page")
        .or(page.title.as_deref())
        .unwrap_or(name);
    let mut header_attrs = format!(" path=\"pages/{name}\"");
    if let Some(tf) = header.and_then(|h| h.title_from.as_ref()) {
        let read = header_reads.get(&tf.section).with_context(|| {
            format!("header.title_from: section `{}` reads nothing", tf.section)
        })?;
        let _ = writeln!(
            script,
            "const title = computed(() => {{\n  const v = rows_{read}.value[0]?.[{}];\n  return v === undefined || v === null ? {} : `{} ${{String(v)}}`;\n}});",
            js(&tf.field),
            js(title),
            title.replace('`', "")
        );
        header_attrs.push_str(" :title=\"title\"");
    } else {
        let _ = write!(header_attrs, " title=\"{}\"", attr(title));
    }
    if let Some(b) = header.and_then(|h| h.badge.as_ref()) {
        let (section, field) = b
            .text
            .strip_prefix("section.")
            .and_then(|r| r.split_once(".row."))
            .with_context(|| {
                format!(
                    "header.badge.text `{}`: only `section.<name>.row.<field>` is generated",
                    b.text
                )
            })?;
        let read = header_reads
            .get(section)
            .with_context(|| format!("header.badge: section `{section}` reads nothing"))?;
        let _ = writeln!(
            script,
            "const badge = computed(() => {{\n  const v = rows_{read}.value[0]?.[{}];\n  return v === undefined || v === null ? '' : String(v);\n}});",
            js(field)
        );
        let _ = write!(
            header_attrs,
            " :badge=\"badge\" badge-field=\"{}\"",
            attr(field)
        );
    }
    let links = header
        .map(|h| h.actions.as_slice())
        .unwrap_or_default()
        .iter()
        .map(|a| {
            if !routes.contains_key(&a.navigate.to) || !a.navigate.params.is_empty() {
                bail!(
                    "header action `{}`: a link to a page without params is generated",
                    a.name
                );
            }
            lib.insert("href");
            Ok(format!(
                "{{ label: {}, href: href({}, {{}}) }}",
                js(a.label.as_deref().unwrap_or(&a.name)),
                js(&a.navigate.to)
            ))
        })
        .collect::<Result<Vec<_>>>()?;
    if !links.is_empty() {
        let _ = writeln!(script, "const links = [{}];", links.join(", "));
        header_attrs.push_str(" :links=\"links\"");
    }

    // The body: the layout's columns, or the sections in order.
    let indent = "    ";
    if let Some(layout) = &page.layout {
        let widths = layout
            .columns
            .iter()
            .map(|c| match c.width.as_deref() {
                Some("narrow") | None => Ok("narrow"),
                Some("wide") => Ok("wide"),
                Some(w) => bail!("layout column `{}`: width `{w}`", c.name),
            })
            .collect::<Result<Vec<_>>>()?;
        let _ = write!(
            header_attrs,
            " :columns=\"[{}]\"",
            widths
                .iter()
                .map(|w| format!("'{w}'"))
                .collect::<Vec<_>>()
                .join(", ")
        );
        for (i, c) in layout.columns.iter().enumerate() {
            let _ = writeln!(body, "{indent}<template #col{i}>");
            for s in &c.sections {
                let m = section_markup.remove(s).with_context(|| {
                    format!("layout column `{}`: section `{s}` is not drawn", c.name)
                })?;
                let _ = writeln!(body, "{indent}  {m}");
            }
            let _ = writeln!(body, "{indent}</template>");
        }
        if let Some(left) = section_markup.keys().next() {
            bail!("section `{left}` stands in no layout column");
        }
    } else {
        for s in &order {
            if let Some(m) = section_markup.remove(s) {
                let _ = writeln!(body, "{indent}{m}");
            }
        }
    }
    if !filters_markup.is_empty() {
        body = format!("{indent}<template #filters>{filters_markup}</template>\n{body}");
    }

    let mut out = String::new();
    let _ = writeln!(out, "<script setup lang=\"ts\">");
    let _ = writeln!(out, "// {HEAD}");
    let _ = writeln!(out, "// Page `{name}`.");
    if script.contains("computed(") {
        let _ = writeln!(out, "import {{ computed }} from 'vue';");
    }
    for i in &imports {
        let _ = writeln!(out, "import {i} from '../../components/spec/{i}.vue';");
    }
    if !lib.is_empty() {
        let names = lib.iter().copied().collect::<Vec<_>>().join(", ");
        let _ = writeln!(out, "import {{ {names} }} from '../../lib/spec.ts';");
    }
    if script.contains("toneMaps[") {
        let _ = writeln!(out, "import {{ toneMaps }} from '../ui.ts';");
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "const props = defineProps<{{ params: Record<string, string> }}>();"
    );
    out.push_str(&script);
    let _ = writeln!(out, "</script>");
    let _ = writeln!(out);
    let _ = writeln!(out, "<template>");
    let _ = writeln!(out, "  <SpecPage{header_attrs}>");
    out.push_str(&body);
    let _ = writeln!(out, "  </SpecPage>");
    let _ = writeln!(out, "</template>");
    Ok(out)
}

/// `state.<key>` as its key.
fn state_key(binds: &str) -> &str {
    binds.strip_prefix("state.").unwrap_or(binds)
}

/// Text for a double-quoted attribute of a template.
fn attr(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('"', "&quot;")
        .replace('<', "&lt;")
}

fn pages_ts(doc: &Doc, routes: &BTreeMap<String, Vec<String>>) -> String {
    let mut out = format!(
        "// {HEAD}\n// The component of each page, by page name.\nimport type {{ Component }} from 'vue';\n"
    );
    for name in doc.pages.keys() {
        let _ = writeln!(
            out,
            "import {} from './pages/{}.vue';",
            pascal(name),
            pascal(name)
        );
    }
    out.push_str("import type { PageName } from './ui.ts';\n\n");
    out.push_str("export const pageComponents: Record<PageName, Component> = {\n");
    for name in routes.keys() {
        let _ = writeln!(out, "  {}: {},", js(name), pascal(name));
    }
    out.push_str("};\n");
    out
}

fn ui_ts(
    doc: &Doc,
    routes: &BTreeMap<String, Vec<String>>,
    views: &BTreeMap<String, ViewRoute>,
    read: &BTreeSet<String>,
    hosts: &BTreeSet<String>,
) -> String {
    let mut out = format!("// {HEAD}\n");
    let _ = writeln!(
        out,
        "// App `{}`: {}.\n",
        doc.app,
        doc.title.as_deref().unwrap_or(&doc.app)
    );
    out.push_str("/** Every page, by name. */\n");
    let _ = writeln!(
        out,
        "export type PageName = {};\n",
        routes.keys().map(|k| js(k)).collect::<Vec<_>>().join(" | ")
    );
    out.push_str("/** The page the app opens on. */\n");
    let _ = writeln!(
        out,
        "export const home: PageName = {};\n",
        js(&doc.navigation.home)
    );
    out.push_str("/** Each page's route below `#/`: a literal segment, or `:<param>`. */\n");
    out.push_str("export const routes: Record<PageName, readonly string[]> = {\n");
    for (name, segs) in routes {
        let _ = writeln!(
            out,
            "  {}: [{}],",
            js(name),
            segs.iter().map(|s| js(s)).collect::<Vec<_>>().join(", ")
        );
    }
    out.push_str("};\n\n");
    out.push_str("/** Every view a page reads, by the route of spec/http.yaml it is read on. */\n");
    out.push_str("export const views = {\n");
    for v in read {
        let r = &views[v];
        let params = r
            .params
            .iter()
            .map(|(var, p)| format!("{}: {}", js(var), js(p)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "  {}: {{ path: {}, params: {{ {params} }}, body: {} }},",
            js(v),
            js(&r.path),
            js(&r.body)
        );
    }
    out.push_str("} as const;\n\n");
    out.push_str("/** A view a page reads. */\nexport type ViewName = keyof typeof views;\n\n");
    out.push_str("/** The tone of each value, by tone map. */\n");
    out.push_str("export const toneMaps: Record<string, Readonly<Record<string, string>>> = {\n");
    for (name, map) in &doc.tone_maps {
        let entries = map
            .iter()
            .map(|(k, v)| format!("{}: {}", js(k), js(v)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "  {}: {{ {entries} }},", js(name));
    }
    out.push_str("};\n\n");
    out.push_str("/** Every host slot of the document: `ui/src/hosts.ts` registers one component for each. */\n");
    let _ = writeln!(
        out,
        "export type HostName = {};",
        hosts.iter().map(|h| js(h)).collect::<Vec<_>>().join(" | ")
    );
    out
}
