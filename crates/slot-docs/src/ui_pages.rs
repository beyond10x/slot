//! Generates the web UI's pages from the UI spec: an `ess-ui/1` document (`spec/ui/slot.ui.yaml`)
//! and the HTTP binding of the specification (`spec/http.yaml`). The output is Vue code under
//! `ui/src/generated/` that composes the hand-written components of `ui/src/components/spec/`:
//! one single-file component per page, `pages.ts` (route to page), and `ui.ts` (the routes, the
//! paths of the views the pages read, the tone maps, and the names of the host slots, which
//! `ui/src/hosts.ts` must register).
//!
//! The reader takes the part of `ess-ui/1` the pages use and refuses every other key by name, so
//! nothing the document says is dropped unseen. `ess ui check` checks the same document against
//! the specification; this module only turns it into code.

