//! Generates slot's derived artifacts. `task check` runs each with `--check`,
//! which fails when the committed file differs from what would be written.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use clap::{CommandFactory, Parser, Subcommand};
use ts_rs::TS;

/// Generate slot's CLI reference, UI types and documentation-site provenance.
#[derive(Debug, Parser)]
#[command(name = "slot-docs", version)]
struct Cli {
    #[command(subcommand)]
    command: Cmd,
}

#[derive(Debug, Subcommand)]
enum Cmd {
    /// Write the CLI reference page (Markdown).
    CliReference {
        /// Output file.
        #[arg(long, default_value = "website/docs/reference/cli.md")]
        out: PathBuf,
        /// Fail instead of writing when the file is out of date.
        #[arg(long)]
        check: bool,
    },
    /// Write the TypeScript types the web UI shares with the daemon.
    TsTypes {
        /// Output file.
        #[arg(long, default_value = "ui/src/generated/types.ts")]
        out: PathBuf,
        /// Fail instead of writing when the file is out of date.
        #[arg(long)]
        check: bool,
    },
    /// Write `.well-known/b10x-site.json` into a built documentation site.
    Provenance {
        /// Built site directory.
        #[arg(long, default_value = "website/build")]
        site: PathBuf,
        /// Commit the site was built from.
        #[arg(long)]
        commit: String,
        /// Base URL of the site.
        #[arg(long, default_value = "/slot/")]
        base_url: String,
    },
}

fn main() -> Result<()> {
    match Cli::parse().command {
        Cmd::CliReference { out, check } => emit(&out, &cli_reference(), check),
        Cmd::TsTypes { out, check } => emit(&out, &ts_types(), check),
        Cmd::Provenance {
            site,
            commit,
            base_url,
        } => {
            let dir = site.join(".well-known");
            std::fs::create_dir_all(&dir)?;
            let doc = serde_json::json!({
                "schema": "b10x-project-site/v1",
                "repository": "slot",
                "commit": commit,
                "baseUrl": base_url,
            });
            std::fs::write(dir.join("b10x-site.json"), serde_json::to_vec_pretty(&doc)?)?;
            Ok(())
        }
    }
}

fn emit(path: &Path, content: &str, check: bool) -> Result<()> {
    if check {
        let current = std::fs::read_to_string(path).unwrap_or_default();
        if current != content {
            bail!(
                "{} is out of date; run `cargo run -q -p b10x-slot-docs -- {}`",
                path.display(),
                if path.extension().is_some_and(|e| e == "ts") {
                    "ts-types"
                } else {
                    "cli-reference"
                }
            );
        }
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, content).with_context(|| format!("write {}", path.display()))
}

fn ts_types() -> String {
    use slot::types::{
        CensusClass, CensusSession, Chunk, Event, HostCensus, Job, JobState, LiveJob, State, Unit,
    };
    let mut s = String::from(
        "// Generated by `slot-docs ts-types` from crates/slot/src/types.rs. Do not edit.\n\n",
    );
    for decl in [
        JobState::decl(),
        Job::decl(),
        Unit::decl(),
        LiveJob::decl(),
        State::decl(),
        CensusClass::decl(),
        CensusSession::decl(),
        HostCensus::decl(),
        Event::decl(),
        Chunk::decl(),
    ] {
        let _ = writeln!(s, "export {decl}\n");
    }
    s.trim_end().to_string() + "\n"
}

fn cli_reference() -> String {
    let mut cmd = slot::cli::Cli::command();
    cmd.build();
    let mut s = String::from(
        "---\ntitle: CLI reference\ndescription: Every slot command and option.\n---\n\n\
         <!-- Generated by `slot-docs cli-reference` from crates/slot/src/cli.rs. Do not edit. -->\n\n",
    );
    render(&cmd, "slot", 2, &mut s);
    s.trim_end().to_string() + "\n"
}

fn render(cmd: &clap::Command, path: &str, level: usize, s: &mut String) {
    let hashes = "#".repeat(level);
    let _ = writeln!(s, "{hashes} `{path}`\n");
    if let Some(about) = cmd.get_long_about().or_else(|| cmd.get_about()) {
        let _ = writeln!(s, "{about}\n");
    }
    let usage = cmd.clone().render_usage().to_string();
    let usage = usage.trim_start_matches("Usage: ").trim();
    let _ = writeln!(s, "```text\n{usage}\n```\n");
    let args: Vec<_> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set() && a.get_id() != "help" && a.get_id() != "version")
        .filter(|a| level == 2 || !a.is_global_set())
        .collect();
    if !args.is_empty() {
        for a in args {
            let name = match (a.get_short(), a.get_long()) {
                (_, Some(l)) => format!("--{l}"),
                (Some(c), None) => format!("-{c}"),
                (None, None) => format!("<{}>", a.get_id().as_str().to_uppercase()),
            };
            let help = a.get_help().map(ToString::to_string).unwrap_or_default();
            let mut extra = Vec::new();
            if let Some(env) = a.get_env() {
                extra.push(format!("env `{}`", env.to_string_lossy()));
            }
            let defaults: Vec<String> = a
                .get_default_values()
                .iter()
                .map(|d| d.to_string_lossy().into_owned())
                .filter(|d| !d.contains('/') || d.starts_with("127."))
                .collect();
            if !defaults.is_empty() {
                extra.push(format!("default `{}`", defaults.join(",")));
            }
            let extra = if extra.is_empty() {
                String::new()
            } else {
                format!(" ({})", extra.join(", "))
            };
            let _ = writeln!(s, "- `{name}`: {help}{extra}");
        }
        s.push('\n');
    }
    for sub in cmd.get_subcommands() {
        if sub.get_name() == "help" || sub.is_hide_set() {
            continue;
        }
        render(sub, &format!("{path} {}", sub.get_name()), level + 1, s);
    }
}
